//! The attached line interface's `/pet` and `/hatch` (spec: pets, Pet
//! slash command; Generating a pet): `/pet` runs in this client, never
//! sent to the daemon's session; `/hatch` is a daemon generate flow
//! (`pets.hatch.*`) billed to the attached session.

use pmt_rpc::client::error_of;
use pmt_rpc::contracts::{
    HatchAnswerParams, HatchStartParams, HatchStep, PetsHatchAnswer, PetsHatchStart,
};

use super::line::Chat;
use super::render::Out as _;
use crate::chat::theme::Role;
use crate::pets_host::slash::{self, Pet};

impl Chat<'_, '_> {
    /// `/pet [list|off|scale <factor>|<slug>]`.
    pub(super) fn pet_command(&mut self, args: &str) {
        let scope = self.start.scope;
        let shown = match Pet::parse(args) {
            Pet::List => Ok(slash::list(scope)),
            other => slash::run(scope, &other),
        };
        match shown {
            Ok(text) => self.screen.notice(&text),
            Err(err) => self.screen.error(&err),
        }
        if let Some(pet) = &self.screen.pet {
            pet.refresh();
        }
    }

    /// `/hatch <description>`: generated by the daemon, which owns the
    /// session's usage ledger (each paid image is a row of this session);
    /// the next lines answer each step.
    pub(super) async fn hatch_command(&mut self, args: &str) {
        if args.trim().is_empty() {
            self.screen.notice("usage: /hatch <description>");
            return;
        }
        let params = HatchStartParams {
            profile: self.start.scope.name().to_string(),
            description: args.to_owned(),
            session_id: Some(self.attached.session.clone()),
        };
        let step = self
            .attached
            .client
            .call_typed::<PetsHatchStart>(&params)
            .await;
        self.hatch_step(step);
    }

    /// The line answers `/hatch`'s question; `false` when none is asked.
    pub(super) async fn hatch_answer(&mut self, line: &str) -> bool {
        let Some(flow) = self.hatch.take() else {
            return false;
        };
        let params = HatchAnswerParams {
            profile: self.start.scope.name().to_string(),
            flow,
            answer: line.to_owned(),
        };
        let step = self
            .attached
            .client
            .call_typed::<PetsHatchAnswer>(&params)
            .await;
        self.hatch_step(step);
        true
    }

    fn hatch_step(&mut self, step: Result<HatchStep, pmt_rpc::RpcError>) {
        match step {
            Ok(step) if !step.done => {
                self.screen.say(Role::Notice, &step.text);
                self.hatch = Some(step.flow);
            }
            Ok(step) => {
                let role = if step.failed {
                    Role::Error
                } else {
                    Role::Notice
                };
                self.screen.say(role, &step.text);
            }
            Err(err) => self.screen.error(&error_of(&err)),
        }
    }
}
