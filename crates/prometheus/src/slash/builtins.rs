//! The built-in slash commands of this build: the cli capability's M1 set
//! and the commands other M1 capabilities define (spec: cli, Built-in
//! slash command set). Commands of later milestones join this table when
//! their owner lands.

use super::{Arg, ArgKind, BusyPolicy, Category, Command, Effect, Surface, TERMINALS};

const fn arg(name: &'static str, kind: ArgKind, required: bool) -> Arg {
    Arg {
        name,
        kind,
        required,
    }
}

const fn text(name: &'static str) -> Arg {
    arg(name, ArgKind::Text, false)
}

const YES: Arg = arg("yes", ArgKind::Flag, false);
const NOW: Arg = arg("now", ArgKind::Flag, false);
const EVERYWHERE: &[Surface] = super::ALL_SURFACES;
/// Commands only messaging platforms have.
const GATEWAY: &[Surface] = &[Surface::Gateway];
/// `/verbose`: terminals, and chats whose display policy lets them cycle
/// tool progress.
const TERMINALS_AND_CHATS: &[Surface] = &[
    Surface::Cli,
    Surface::Tui,
    Surface::Desktop,
    Surface::Gateway,
];
/// `/voice`: voice mode on the interactive surfaces, the per-chat reply
/// mode in chats (spec: voice-mode).
const VOICE: &[Surface] = &[
    Surface::Cli,
    Surface::Tui,
    Surface::Desktop,
    Surface::Gateway,
];
/// Profile-wide reports: the interactive surfaces, never a chat.
const INTERACTIVE: &[Surface] = &[
    Surface::Cli,
    Surface::Tui,
    Surface::Desktop,
    Surface::Dashboard,
];
const CHATS: &[Surface] = &[
    Surface::Cli,
    Surface::Tui,
    Surface::Gateway,
    Surface::Desktop,
    Surface::Acp,
];

/// Builds one entry.
#[allow(clippy::too_many_arguments)]
const fn command(
    name: &'static str,
    aliases: &'static [&'static str],
    category: Category,
    key: &'static str,
    args: &'static [Arg],
    surfaces: &'static [Surface],
    busy: BusyPolicy,
    effect: Effect,
) -> Command {
    Command {
        name,
        aliases,
        category,
        key,
        args,
        surfaces,
        busy,
        effect,
    }
}

