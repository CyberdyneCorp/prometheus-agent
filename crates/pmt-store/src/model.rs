//! Typed session-record values (spec: session-storage, Session record and
//! source enum). Each enum's wire names match the CHECK constraints in
//! `schema/v1.sql`; parsing an unknown name fails with `store.invalid_enum`
//! naming the field and the allowed values.

use std::fmt;
use std::str::FromStr;

use pmt_core::error::{Error, codes};
use pmt_core::id::SessionId;
use serde::{Deserialize, Serialize};

macro_rules! store_enum {
    ($(#[$attr:meta])* $name:ident, $field:literal { $($(#[$vattr:meta])* $variant:ident = $wire:literal),+ $(,)? }) => {
        $(#[$attr])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
        #[serde(rename_all = "snake_case")]
        pub enum $name {
            $($(#[$vattr])* $variant),+
        }

        impl $name {
            /// Every value, in declaration order.
            pub const ALL: &'static [Self] = &[$(Self::$variant),+];
            /// The column this enum is stored in.
            pub const FIELD: &'static str = $field;

            /// The stored name.
            #[must_use]
            pub const fn as_str(self) -> &'static str {
                match self {
                    $(Self::$variant => $wire),+
                }
            }
        }

        impl FromStr for $name {
            type Err = Error;

            fn from_str(text: &str) -> Result<Self, Error> {
                match text {
                    $($wire => Ok(Self::$variant),)+
                    _ => Err(invalid_enum(Self::FIELD, text, &[$($wire),+])),
                }
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str(self.as_str())
            }
        }
    };
}

fn invalid_enum(field: &str, value: &str, allowed: &[&str]) -> Error {
    Error::new(
        &codes::STORE_INVALID_ENUM,
        format!(
            "invalid {field} '{value}' (allowed: {})",
            allowed.join(", ")
        ),
    )
}

store_enum!(
    /// The surface or subsystem that created a session.
    Source, "source" {
        /// Line-mode CLI.
        Cli = "cli",
        /// Terminal UI.
        Tui = "tui",
        /// Messaging gateway.
        Gateway = "gateway",
        /// Scheduled job.
        Cron = "cron",
        /// Delegated child agent.
        Subagent = "subagent",
        /// ACP client.
        Acp = "acp",
        /// OpenAI-compatible API server.
        Api = "api",
        /// Desktop app.
        Desktop = "desktop",
        /// Web dashboard.
        Dashboard = "dashboard",
        /// `prometheus eval`.
        Eval = "eval",
        /// Harness evolution rollouts.
        Harness = "harness",
        /// Imported from an export or another agent.
        Import = "import",
    }
);

store_enum!(
    /// Why a session ended.
    EndReason, "end_reason" {
        /// The user quit.
        UserExit = "user_exit",
        /// The user started a new session.
        NewSession = "new_session",
        /// Continued in a compression child.
        Compression = "compression",
        /// A budget ran out.
        BudgetExhausted = "budget_exhausted",
        /// An unrecoverable error.
        Error = "error",
        /// Cancelled mid-turn.
        Interrupted = "interrupted",
        /// Idle too long.
        IdleTimeout = "idle_timeout",
        /// A scheduled job finished.
        JobComplete = "job_complete",
    }
);

store_enum!(
    /// Archive state: none, by the user, or automatic (cleared on resume).
    Archived, "archived" {
        /// Not archived.
        None = "none",
        /// Archived by the user; kept on resume.
        User = "user",
        /// Archived by idle maintenance; cleared on resume.
        Auto = "auto",
    }
);

store_enum!(
    /// Where a title came from, in increasing precedence.
    TitleSource, "title_source" {
        /// Derived from the first message.
        Derived = "derived",
        /// Generated by the auxiliary model.
        Llm = "llm",
        /// Set by the user.
        User = "user",
    }
);

store_enum!(
    /// How a child session relates to its parent.
    LineageKind, "lineage_kind" {
        /// Continuation after compression.
        Compression = "compression",
        /// Branched copy.
        Fork = "fork",
        /// Delegated child agent.
        Delegate = "delegate",
        /// `/new`-style reset keeping the lineage.
        Reset = "reset",
        /// Imported session.
        Import = "import",
    }
);

store_enum!(
    /// A message's author role.
    Role, "role" {
        /// System prompt.
        System = "system",
        /// The user.
        User = "user",
        /// The model.
        Assistant = "assistant",
        /// A tool result.
        Tool = "tool",
    }
);

store_enum!(
    /// How a usage row's cost is known (model-providers).
    CostStatus, "cost_status" {
        /// Reported by the provider.
        Exact = "exact",
        /// Computed from the model price table.
        Estimated = "estimated",
        /// Covered by a subscription.
        Subscription = "subscription",
        /// Not priced (`cost_usd` null).
        Unknown = "unknown",
    }
);

impl TitleSource {
    /// Precedence: an automatic title replaces only a strictly lower one.
    #[must_use]
    pub const fn rank(self) -> u8 {
        match self {
            Self::Derived => 0,
            Self::Llm => 1,
            Self::User => 2,
        }
    }
}

/// Typed origin of a session, beside its `source` (never encoded in the id).
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case", deny_unknown_fields)]
pub enum Origin {
    /// No further origin (CLI, TUI, desktop...).
    #[default]
    None,
    /// A messaging conversation.
    Gateway {
        /// Platform name (`telegram`, `discord`...).
        platform: String,
        /// Chat or channel id.
        chat: String,
        /// Thread id, when threaded.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        thread: Option<String>,
        /// Sender id.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        user: Option<String>,
    },
    /// A scheduled job run.
    Cron {
        /// The job id.
        job_id: String,
    },
    /// A delegated child of another session.
    Subagent {
        /// The delegating session.
        parent: SessionId,
    },
}

impl Origin {
    /// The scheduled job id, for cron sessions.
    #[must_use]
    pub fn job_id(&self) -> Option<&str> {
        match self {
            Self::Cron { job_id } => Some(job_id),
            _ => None,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::{EndReason, LineageKind, Role, Source};

    #[test]
    fn unknown_source_names_field_and_allowed_values() {
        let err = "telegrm".parse::<Source>().unwrap_err();
        assert_eq!(err.code().code, "store.invalid_enum");
        assert!(err.message().contains("source 'telegrm'"), "{err}");
        assert!(err.message().contains("cli, tui, gateway, cron"), "{err}");
    }

    #[test]
    fn names_round_trip() {
        for value in Source::ALL {
            assert_eq!(value.as_str().parse::<Source>().unwrap(), *value);
        }
        for value in EndReason::ALL {
            assert_eq!(value.as_str().parse::<EndReason>().unwrap(), *value);
        }
        assert!("sideways".parse::<LineageKind>().is_err());
        assert!("bot".parse::<Role>().is_err());
    }
}
